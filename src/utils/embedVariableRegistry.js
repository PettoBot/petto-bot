const camel = (text) => {
  const words = text.split(/[^A-Za-z0-9]+/).filter(Boolean);
  return words[0].toLowerCase() + words.slice(1).map((word) => word[0].toUpperCase() + word.slice(1)).join('');
};
const variableKey = (groupId, tok) => `embeds.var.${camel(groupId)}.${tok.replace(/^\{|\}$/g, '').split('.').map(camel).join('.')}`;

/** The groups with their label and descriptions in `lang`. */
function describeGroups(lang) {
  return GROUPS.map((group) => ({
    id: group.id,
    label: t(lang, `embeds.varGroup.${camel(group.id)}`),
    availability: group.availability,
    vars: group.vars.map((entry) => {
      if (typeof entry === 'string') return { tok: entry, desc: t(lang, variableKey(group.id, entry)) };
      // The extra quest variables describe themselves in each language.
      if (entry.describe) return { tok: entry.tok, desc: entry.describe(lang) };
      if (entry.desc !== undefined) return { tok: entry.tok, desc: entry.desc };
      return { tok: entry.tok, desc: t(lang, variableKey(group.id, entry.tok)), dynamic: true };
    }),
  }));
}

const VARIABLE_GROUPS = describeGroups('en');

/** A copy of the list, with the labels and descriptions in `lang` (English outside of a command or event). */
function listVariables(lang = currentLanguage()) {
  return describeGroups(lang);
}

module.exports = { VARIABLE_GROUPS, listVariables };
